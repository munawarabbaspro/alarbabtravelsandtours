"""v26 - remove the unscoped "98% approval" claim and "guaranteed" wording from the source data (data/site-data.json).
The only place the success rate is now shown is on Asian visit visa pages, generated by build.py with its own wording and note.

  py tools/patch_v26.py --dry    show every change, write nothing
  py tools/patch_v26.py          apply (idempotent: a second run changes nothing)
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = os.path.join(ROOT, "data", "site-data.json")
raw = open(P, encoding="utf-8").read()
d = json.loads(raw)
rt = json.dumps(d, ensure_ascii=False, indent=1)
print("round trip identical to the file on disk:", rt == raw or rt + "\n" == raw)

AP = r"Pakistan['’]s (?:#1|top) visa (?:agency|consultant)"
RULES = [
    (re.compile(r"\s+with " + AP), ""),                                   # "... from Islamabad with Pakistan's #1 visa agency."
    (re.compile(r"\s+by " + AP), " by our Blue Area visa team"),          # "Expert documentation by Pakistan's #1 visa agency."
    (re.compile(r"\s*" + AP + r"(?: with 98\s?% approval rate)?\.?"), ""),# stand-alone sentence
    (re.compile(r"\s+with 98\s?% approval rate"), ""),                    # "visit visas with 98% approval rate."
    (re.compile(r"\s*98\s?% approval rate(?: from [^.]+)?\.?"), ""),      # stand-alone "98% approval rate." / "... from Blue Area, Islamabad."
    (re.compile(r"and high approval rates"), "and a free document check"),
    (re.compile(r"\bfor a guaranteed smooth entry"), "for a smooth entry"),
]

def clean(s):
    o = s
    for rx, rep in RULES:
        s = rx.sub(rep, s)
    if s != o:
        s = re.sub(r"\s{2,}", " ", s).replace(" .", ".").replace("..", ".").strip()
        if s and s[-1] not in ".!?": s += "."
    return s

changes = []
def walk(o, path=""):
    if isinstance(o, dict):
        for k, v in o.items():
            if isinstance(v, str):
                n = clean(v)
                if n != v: changes.append((path + "/" + k, v, n)); o[k] = n
            else: walk(v, path + "/" + k)
    elif isinstance(o, list):
        for i, v in enumerate(o):
            if isinstance(v, str):
                n = clean(v)
                if n != v: changes.append((path + f"[{i}]", v, n)); o[i] = n
            else: walk(v, path + f"[{i}]")
walk(d)
for p, a, b in changes:
    print("-", p); print("   BEFORE:", a[:230]); print("   AFTER: ", b[:230])
print("\nstrings changed:", len(changes))
left = [(p, m.group(0)) for p, a, b in changes for m in re.finditer(r"98\s?%|#1|guarant|approval rate", b, re.I)]
print("claim words still present in the changed strings:", left)
if "--dry" in sys.argv:
    print("DRY RUN - nothing written"); sys.exit()
open(P, "w", encoding="utf-8").write(json.dumps(d, ensure_ascii=False, indent=1) + ("\n" if raw.endswith("\n") else ""))
print("written", P)
